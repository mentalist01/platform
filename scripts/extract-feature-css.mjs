import fs from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';

const sourcePath = path.resolve('src/index.css');
const destinations = [
  {
    filename: 'src/components/NotesSection.css',
    matches: (selector) => /\.notes-explorer-shell(?:--workspace-v2)?(?:[^\w-]|$)/.test(selector),
  },
  {
    filename: 'src/components/CallSection.css',
    matches: (selector) => /\.call-[\w-]+/.test(selector),
  },
  {
    filename: 'src/components/ChatSections.css',
    matches: (selector) => /\.(?:student-chat|teacher-chat)-[\w-]+/.test(selector),
  },
  {
    filename: 'src/components/TeacherCalendarSection.css',
    matches: (selector) => /\.teacher-calendar-[\w-]+/.test(selector),
  },
].map((destination) => ({
  ...destination,
  path: path.resolve(destination.filename),
  root: null,
  parentClones: new WeakMap(),
  ruleCount: 0,
}));

const splitSelectorBranches = (selector) => {
  const branches = [];
  let current = '';
  let quote = '';
  let escaped = false;
  let roundDepth = 0;
  let squareDepth = 0;

  for (const character of selector) {
    if (escaped) {
      current += character;
      escaped = false;
      continue;
    }
    if (character === '\\') {
      current += character;
      escaped = true;
      continue;
    }
    if (quote) {
      current += character;
      if (character === quote) quote = '';
      continue;
    }
    if (character === '"' || character === "'") {
      current += character;
      quote = character;
      continue;
    }
    if (character === '(') roundDepth += 1;
    if (character === ')') roundDepth = Math.max(0, roundDepth - 1);
    if (character === '[') squareDepth += 1;
    if (character === ']') squareDepth = Math.max(0, squareDepth - 1);
    if (character === ',' && roundDepth === 0 && squareDepth === 0) {
      branches.push(current.trim());
      current = '';
      continue;
    }
    current += character;
  }
  if (current.trim()) branches.push(current.trim());
  return branches;
};

const ensureDestinationParent = (destination, sourceParent) => {
  if (!sourceParent || sourceParent.type === 'root') return destination.root;
  const existing = destination.parentClones.get(sourceParent);
  if (existing) return existing;
  const parent = ensureDestinationParent(destination, sourceParent.parent);
  const clone = sourceParent.clone({ nodes: [] });
  parent.append(clone);
  destination.parentClones.set(sourceParent, clone);
  return clone;
};

for (const destination of destinations) {
  try {
    destination.root = postcss.parse(await fs.readFile(destination.path, 'utf8'), {
      from: destination.path,
    });
    destination.root.walkComments((comment) => {
      if (comment.text.includes('Generated by scripts/extract-feature-css.mjs')) comment.remove();
    });
  } catch (error) {
    if (error?.code !== 'ENOENT') throw error;
    destination.root = postcss.root();
  }
}

const root = postcss.parse(await fs.readFile(sourcePath, 'utf8'), { from: sourcePath });
root.walkRules((rule) => {
  const branches = splitSelectorBranches(rule.selector || '');
  if (!branches.length) return;
  const matches = destinations.filter((destination) => branches.every(destination.matches));
  if (matches.length !== 1) return;
  const [destination] = matches;
  ensureDestinationParent(destination, rule.parent).append(rule.clone());
  destination.ruleCount += 1;
  rule.remove();
});

root.walkAtRules((atRule) => {
  if (Array.isArray(atRule.nodes) && atRule.nodes.length === 0) atRule.remove();
});

await fs.writeFile(sourcePath, root.toString());
for (const destination of destinations) {
  const header = '/* Loaded only with this lazy platform section. Generated by scripts/extract-feature-css.mjs. */\n';
  const extractedCss = destination.root.toString().trim();
  await fs.writeFile(destination.path, `${header}${extractedCss}\n`);
  console.log(`[css-split] ${destination.filename}: ${destination.ruleCount} rules`);
}
